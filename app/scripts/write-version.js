// Stamp the app version (from package.json) where the web app can read it.
const fs = require("fs");
const path = require("path");
const { version } = require("../package.json");
fs.writeFileSync(
  path.join(__dirname, "..", "www", "version.js"),
  `// Generated by scripts/write-version.js from package.json. Don't edit.\nwindow.LEAGUE_FINDER_VERSION = "${version}";\n`,
);
console.log(`Wrote version.js (${version})`);
